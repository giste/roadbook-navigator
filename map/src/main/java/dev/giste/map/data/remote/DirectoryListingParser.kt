package dev.giste.map.data.remote

import dev.giste.map.domain.FileSize
import dev.giste.map.domain.RemoteMapEntry
import dev.giste.map.domain.isSafeRemoteName
import java.net.URI
import java.net.URISyntaxException
import java.time.LocalDate
import java.time.format.DateTimeParseException

/**
 * Reads the HTML folder listing of a web server, in the table form of Apache's autoindex (as the
 * mapsforge download server serves it), into folders and map files.
 *
 * Each row of the table holds an icon, a link to the entry, the date it changed, its size and a
 * description:
 *
 * ```
 * <tr><td valign="top"><img src="/icons/unknown.gif" alt="[   ]"></td><td><a href="andorra.map">andorra.map</a>
 *   </td><td align="right">2026-09-07 15:30  </td><td align="right">2.4M</td><td>&nbsp;</td></tr>
 * ```
 *
 * A link that ends in `/` is a folder. Links to other places (the parent folder, the sort links of
 * the header, other servers) and files other than `.map` files are left out, as are names that are
 * not safe on the device (see [isSafeRemoteName]). A date or size that cannot be read is left
 * empty rather than dropping the entry.
 *
 * It is a small parser rather than an HTML library: the listing is generated by the server, so
 * its form is regular, and the tests cover it with real listings.
 */
internal object DirectoryListingParser {

    /** Apache titles its listings "Index of /path". */
    private val LISTING_TITLE = Regex("""<title>\s*Index of\b""", RegexOption.IGNORE_CASE)

    private val ROW = Regex("""<tr[^>]*>(.*?)</tr>""", setOf(RegexOption.IGNORE_CASE, RegexOption.DOT_MATCHES_ALL))
    private val CELL = Regex("""<td[^>]*>(.*?)</td>""", setOf(RegexOption.IGNORE_CASE, RegexOption.DOT_MATCHES_ALL))
    private val LINK = Regex("""<a\s+href="([^"]*)"""", RegexOption.IGNORE_CASE)

    /** Apache's dates: `2026-09-07 15:30`. Only the day is kept. */
    private val DATE = Regex("""^(\d{4}-\d{2}-\d{2})\b""")

    /** Apache's rounded sizes: `812`, `2.4M`, `3.3G`. A folder's size is `-`. */
    private val SIZE = Regex("""^(\d+(?:\.\d+)?)([KMGT]?)$""")

    /** The cells of a listing row: icon, link, date, size (and a description, not used). */
    private const val LINK_CELL = 1
    private const val DATE_CELL = 2
    private const val SIZE_CELL = 3

    private const val MAP_FILE_SUFFIX = ".map"
    private const val FOLDER_SUFFIX = "/"

    /** Apache's size units are powers of 1024: K, M, G, T. */
    private const val UNITS = "KMGT"
    private const val UNIT_FACTOR = 1024.0

    /**
     * Reads [html] as a folder listing.
     *
     * @param html the page the server sent for a folder.
     * @return its folders first, then its map files, each group in the page's order; or `null` if
     * the page is not a folder listing.
     */
    fun parse(html: String): List<RemoteMapEntry>? {
        if (!LISTING_TITLE.containsMatchIn(html)) return null
        val entries = ROW.findAll(html)
            .mapNotNull { row -> CELL.findAll(row.groupValues[1]).map { it.groupValues[1] }.toList().toEntry() }
            .toList()
        // sortedBy is stable, so each group keeps the page's order.
        return entries.sortedBy { it !is RemoteMapEntry.Folder }
    }

    /** The entry of a row with these cells, or `null` if it is not a folder or a map file. */
    private fun List<String>.toEntry(): RemoteMapEntry? {
        val href = getOrNull(LINK_CELL)?.let { LINK.find(it)?.groupValues?.get(1) } ?: return null
        val name = href.toLocalName() ?: return null
        return when {
            href.endsWith(FOLDER_SUFFIX) -> RemoteMapEntry.Folder(name).takeIf { isSafeRemoteName(name) }
            name.endsWith(MAP_FILE_SUFFIX, ignoreCase = true) && isSafeRemoteName(name) ->
                RemoteMapEntry.MapFile(
                    name = name,
                    approximateSize = getOrNull(SIZE_CELL)?.toSize(),
                    modified = getOrNull(DATE_CELL)?.toDate(),
                )
            else -> null
        }
    }

    /**
     * The name this link points to inside the listed folder, decoded (`%20` is a space), or
     * `null` if it points elsewhere: an absolute path such as the parent folder, a query such as
     * a sort link, another server, or a deeper path.
     */
    private fun String.toLocalName(): String? {
        if (startsWith("/") || startsWith("?") || startsWith("#")) return null
        val uri = try {
            URI(this)
        } catch (_: URISyntaxException) {
            return null
        }
        if (uri.isAbsolute || uri.rawQuery != null || uri.rawFragment != null) return null
        val path = uri.path?.removeSuffix(FOLDER_SUFFIX) ?: return null
        return path.takeUnless { it.isEmpty() || it.contains('/') }
    }

    /** This cell's size in bytes, or `null` if it lists none. Rounded sizes stay rounded. */
    private fun String.toSize(): FileSize? {
        val match = SIZE.find(trim()) ?: return null
        val (number, unit) = match.destructured
        val exponent = if (unit.isEmpty()) 0 else UNITS.indexOf(unit) + 1
        var bytes = number.toDouble()
        repeat(exponent) { bytes *= UNIT_FACTOR }
        return FileSize(bytes.toLong())
    }

    /** This cell's day, or `null` if it lists none. */
    private fun String.toDate(): LocalDate? {
        val day = DATE.find(trim())?.groupValues?.get(1) ?: return null
        return try {
            LocalDate.parse(day)
        } catch (_: DateTimeParseException) {
            // Shaped like a date but not one, e.g. 2026-13-40.
            null
        }
    }
}
